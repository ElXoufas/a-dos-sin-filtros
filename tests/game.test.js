'use strict';
const {test, before, after} = require('node:test');
const assert = require('node:assert/strict');
const { server } = require('../server');
const { cards, cameraCards } = require('../cards');
let url;
before(async () => {
  await new Promise(r => server.listen(0, '127.0.0.1', r));
  url = `http://127.0.0.1:${server.address().port}`;
});
after(async () => {
  server.closeAllConnections();
  await new Promise(r => server.close(r));
});
async function post(route, data, status=200) {
  const res = await fetch(url+route,{method:'POST',headers:{'content-type':'application/json'},body:JSON.stringify(data)});
  const body = await res.json();
  assert.equal(res.status,status,JSON.stringify(body));
  return body;
}
function action(identity, type, value, status=200) {
  return post('/api/action',{room:identity.room,token:identity.token,type,value},status);
}
