test('dos usuarios pueden jugar sincronizados con privacidad y reglas',async()=>{
  const health = await fetch(url+'/api/health');
  assert.equal((await health.json()).ok,true);
  const home = await fetch(url+'/');
  assert.equal(home.status,200);
  assert.ok((await home.text()).includes('Vuestra noche'));
  await post('/api/create',{name:'Sin edad',adult:false},400);
  const a = await post('/api/create',{name:'Ana <script>',adult:true,level:'intenso',cameraEnabled:true,mediaConsent:true});
  assert.match(a.room,/^[A-Z2-9]{6}$/);
  assert.equal(a.state.players[0].name,'Ana script');
  assert.equal(a.state.settings.cameraActive,false);
  await action(a,'start',undefined,400);
  const b = await post('/api/join',{name:'Alex',adult:true,code:a.room,mediaConsent:false});
  assert.equal(b.state.players.length,2);
  assert.equal(b.state.settings.cameraActive,false);
  await post('/api/join',{name:'Otras',adult:true,code:a.room},409);
  await action(b,'settings',{level:'chispa'},403);
  await action(a,'settings',{level:'fuego'});
  const custom = await action(b,'addCard',{kind:'dare',media:'foto',text:'Graba una foto de vuestro momento favorito.'});
  assert.equal(custom.state.settings.customCount,1);
  await action(a,'addCard',{kind:'truth',text:'¿Cuál fue nuestro mejor momento juntos?'});
  await action(a,'addCard',{kind:'truth',text:'x'},400);
  const consent = await action(b,'mediaConsent',true);
  assert.equal(consent.state.settings.cameraActive,true);
  await action(a,'ready',true);
  const ready = await action(b,'ready',true);
  assert.equal(ready.state.players.every(p=>p.ready),true);
  const start = await action(a,'start');
  assert.equal(start.state.game.started,true);
  const turnId = start.state.game.turn;
  const first = turnId === a.playerId?a:b;
  const second = turnId === a.playerId?b:a;
  await action(second,'pick','truth',403);
  const pick = await action(first,'pick','truth');
  assert.equal(pick.state.game.card.kind,'truth');
  assert.equal(pick.state.game.stage,'prompt');
  assert.ok(pick.state.game.card.text.length>10);
  const timer = await action(first,'timer');
  assert.ok(timer.state.game.timerEnd>Date.now());
  const done = await action(first,'finish');
  assert.equal(done.state.game.turn,second.playerId);
  assert.equal(done.state.game.round,2);
  assert.equal(done.state.players.find(x=>x.id===first.playerId).points,1);
  assert.equal(done.state.game.history.length,1);
  const skipPick = await action(second,'pick','dare');
  assert.equal(skipPick.state.game.card.kind,'dare');
  const skipped = await action(second,'skip');
  assert.equal(skipped.state.game.turn,first.playerId);
  assert.equal(skipped.state.players.find(x=>x.id===second.playerId).points,0);
  const closeCamera = await action(second,'mediaConsent',false);
  assert.equal(closeCamera.state.settings.cameraActive,false);
  const another = await action(first,'pick','dare');
  assert.equal(another.state.game.card.media,null);
  await action(first,'finish');
  const restart = await action(a,'restart');
  assert.equal(restart.state.game.started,false);
  assert.equal(restart.state.players[0].points,0);
  const left = await post('/api/leave',{room:b.room,token:b.token});
  assert.equal(left.ok,true);
  const state = await fetch(`${url}/api/state?room=${a.room}&token=${a.token}`);
  assert.equal((await state.json()).state.players.length,1);
  await post('/api/leave',{room:a.room,token:a.token});
  const gone = await fetch(`${url}/api/state?room=${a.room}&token=${a.token}`);
  assert.equal(gone.status,404);
});
test('eventos en tiempo real llegan por SSE a los dos participantes', async()=>{
  const a = await post('/api/create',{name:'Uno',adult:true});
  const b = await post('/api/join',{name:'Dos',adult:true,code:a.room});
  const controller = new AbortController();
  const stream = await fetch(`${url}/api/events?room=${a.room}&token=${a.token}`,{signal:controller.signal});
  assert.equal(stream.status,200);
  const reader = stream.body.getReader();
  const chunk = await reader.read();
  const text = new TextDecoder().decode(chunk.value);
  assert.ok(text.includes('event: state'),text);
  await action(b,'ready',true);
  const chunk2 = await reader.read();
  const eventText = new TextDecoder().decode(chunk2.value);
  assert.ok(eventText.includes('"ready":true'),eventText);
  controller.abort();
  await post('/api/leave',{room:a.room,token:a.token});
});
